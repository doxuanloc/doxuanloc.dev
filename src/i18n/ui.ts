export function getLangFromUrl(url: URL): Lang {
  const seg = url.pathname.split('/').filter(Boolean)[0];
  if (seg === 'vi') return 'vi';
  if (seg === 'ja') return 'ja';
  return 'en';
}

export function useTranslations(lang: Lang) {
  return function t(key: keyof (typeof ui)['en'], vars?: Record<string, string | number>): string {
    let s: string = (ui[lang] as any)[key] ?? (ui.en as any)[key] ?? String(key);
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

/** Tạo đường dẫn theo locale: en -> /path, vi -> /vi/path, ja -> /ja/path. */
export function localizedPath(path: string, lang: Lang): string {
  const clean = '/' + path.replace(/^\//, '');
  if (lang === 'vi') return '/vi' + (clean === '/' ? '' : clean);
  if (lang === 'ja') return '/ja' + (clean === '/' ? '' : clean);
  return clean;
}
